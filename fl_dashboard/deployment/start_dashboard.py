"""Start a configured local console or a separate passwordless LAN reader."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import socket
import subprocess
import sys

from fl_dashboard.projects.project_registry import ProjectRegistry
from fl_dashboard.services.share_server import _validate_anonymous_lan, load_tls_context

from fl_dashboard.paths import APP_ROOT


class StartupError(ValueError):
    pass


def port_number(value: str | int) -> int:
    try:
        port = int(value)
    except (TypeError, ValueError) as exc:
        raise StartupError("Port must be an integer from 1 to 65535.") from exc
    if isinstance(value, bool) or not 1 <= port <= 65535:
        raise StartupError("Port must be an integer from 1 to 65535.")
    return port


def load_launch(path: Path, *, app_root: Path = APP_ROOT) -> tuple[Path, Path, int]:
    try:
        config = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        raise StartupError("Cannot read launch configuration. Run python -B scripts/configure.py first, or select --config.") from exc
    if not isinstance(config, dict):
        raise StartupError("Launch configuration must be a JSON object.")
    python = config.get("python")
    arguments = config.get("arguments")
    directory = config.get("working_directory")
    if not isinstance(python, str) or not Path(python).is_absolute() or not Path(python).is_file():
        raise StartupError("Configured Python is unavailable; rerun configure.py with this machine's Python.")
    if not isinstance(directory, str) or Path(directory).resolve() != app_root.resolve():
        raise StartupError("Configuration belongs to another app directory; rerun configure.py after moving the checkout.")
    if (not isinstance(arguments, list) or len(arguments) not in (10, 14)
            or any(not isinstance(item, str) or any(c in item for c in "\0\r\n") for item in arguments)
            or arguments[:2] != ["-u", "-B"]
            or Path(arguments[2]).resolve() != (app_root / "scripts" / "flflow.py").resolve()
            or arguments[3:5] != ["serve", "--projects-config"]
            or arguments[6:9] != ["--host", "127.0.0.1", "--port"]):
        raise StartupError("Expected the loopback launch.json generated by configure.py.")
    if len(arguments) == 14:
        _share_arguments(arguments[10:])
    projects = Path(arguments[5])
    if not projects.is_absolute() or not projects.is_file():
        raise StartupError("Project configuration is unavailable; rerun configure.py or check its paths.")
    return Path(python), projects, port_number(arguments[9])


def _share_arguments(arguments: list[str]) -> dict[str, str]:
    if not arguments:
        return {}
    if len(arguments) != 4 or set(arguments[::2]) != {"--access-shares-file", "--share-public-url"}:
        raise StartupError("Launch sharing options must specify the share file and HTTPS public URL together.")
    options = dict(zip(arguments[::2], arguments[1::2]))
    from fl_dashboard.services.access_shares import validate_public_url
    from urllib.parse import urlsplit
    try:
        options["--share-public-url"] = validate_public_url(options["--share-public-url"])
        if urlsplit(options["--share-public-url"]).path or not Path(options["--access-shares-file"]).is_absolute():
            raise ValueError("Use a root HTTPS URL and an absolute share file path.")
    except ValueError as exc:
        raise StartupError(str(exc)) from exc
    return options


def check_projects(path: Path) -> None:
    registry = None
    try:
        # Configuration checks never initialize a task executor or contact GitHub.
        registry = ProjectRegistry.from_config(path, read_only=True)
        for project in registry.projects:
            if project.monitor_error or project.monitor is None:
                raise StartupError(f"Project '{project.id}' cannot load its monitor; check its repository and configuration.")
            project.monitor._head(project.default_branch)
    except StartupError:
        raise
    except Exception as exc:
        # Git diagnostics can include credential-bearing URLs; keep them local.
        raise StartupError("Cannot validate project repositories or target refs. Check paths and fetch the configured remote branch.") from exc
    finally:
        if registry is not None:
            registry.close()


def check_port(host: str, port: int) -> None:
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
            if hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
                listener.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
            listener.bind((host, port))
    except OSError as exc:
        raise StartupError(f"Cannot listen on {host}:{port}. Check that the address belongs to this machine and choose an unused port.") from exc


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument("--config", type=Path, default=APP_ROOT / "runs" / "configured" / "launch.json",
                        help="launch.json generated by configure.py.")
    result.add_argument("--port", type=port_number, help="Override the local console port.")
    result.add_argument("--check-only", action="store_true", help="Validate configuration and port without starting any service or task.")
    result.add_argument("--lan", action="store_true", help="Start a separate passwordless, read-only HTTPS service.")
    result.add_argument("--lan-ip", help="Specific RFC1918 IPv4 address on this machine.")
    result.add_argument("--lan-port", type=port_number, help="LAN reader port (default: 8767).")
    result.add_argument("--tls-cert", type=Path, help="PEM certificate whose SAN includes --lan-ip.")
    result.add_argument("--tls-key", type=Path, help="Matching unencrypted PEM private key.")
    result.add_argument("--refresh-interval", type=int, help="LAN refresh interval: 0 disables periodic refresh, or at least 30 seconds (default: 300).")
    result.add_argument("--enable-access-sharing", action="store_true", help="Enable revocable full-access links; normal LAN visits remain read-only.")
    result.add_argument("--share-public-url", help="HTTPS LAN root URL (required for local link management).")
    result.add_argument("--access-shares-file", type=Path, help="Shared grant store; defaults to runs/access-sharing/grants.json.")
    return result


def prepare(args, *, app_root: Path = APP_ROOT) -> tuple[list[str], str]:
    python, projects, configured_port = load_launch(args.config, app_root=app_root)
    saved_sharing = _share_arguments(json.loads(args.config.read_text(encoding="utf-8-sig"))["arguments"][10:])
    if args.lan:
        if args.port is not None:
            raise StartupError("Use --lan-port for the LAN reader.")
        if not args.lan_ip or args.tls_cert is None or args.tls_key is None:
            raise StartupError("LAN mode requires --lan-ip, --tls-cert and --tls-key.")
        try:
            # Reject broad/public bindings before reading certificate files.
            _validate_anonymous_lan(args.lan_ip, tls_context=True)
            load_tls_context(str(args.tls_cert), str(args.tls_key))
        except ValueError as exc:
            raise StartupError(str(exc)) from exc
        refresh = 300 if args.refresh_interval is None else args.refresh_interval
        if refresh != 0 and refresh < 30:
            raise StartupError("Refresh interval must be 0 or at least 30 seconds.")
        host, port = args.lan_ip, args.lan_port or 8767
        command = [str(python), "-u", "-B", str(app_root / "scripts" / "share_server.py"),
                   "--projects-config", str(projects), "--host", host, "--port", str(port),
                   "--control-url", f"http://127.0.0.1:{configured_port}",
                   "--anonymous-lan", "--tls-cert", str(args.tls_cert.resolve()),
                   "--tls-key", str(args.tls_key.resolve()), "--refresh-interval", str(refresh)]
        scheme = "https"
    else:
        if any(value is not None for value in (args.lan_ip, args.lan_port, args.tls_cert, args.tls_key, args.refresh_interval)):
            raise StartupError("LAN address, TLS and refresh options require --lan.")
        host, port = "127.0.0.1", args.port or configured_port
        command = [str(python), "-u", "-B", str(app_root / "scripts" / "flflow.py"), "serve",
                   "--projects-config", str(projects), "--host", host, "--port", str(port)]
        scheme = "http"
    if args.enable_access_sharing or saved_sharing:
        from fl_dashboard.services.access_shares import validate_public_url
        public_url = args.share_public_url or saved_sharing.get("--share-public-url") or (f"https://{host}:{port}" if args.lan else None)
        try:
            public_url = validate_public_url(public_url)
            from urllib.parse import urlsplit
            if urlsplit(public_url).path:
                raise ValueError("Access sharing requires an HTTPS root URL without a path prefix")
        except ValueError as exc:
            raise StartupError("Set --share-public-url to the HTTPS LAN root URL. " + str(exc)) from exc
        store = Path(args.access_shares_file or saved_sharing.get("--access-shares-file") or app_root / "runs" / "access-sharing" / "grants.json").resolve()
        command += ["--access-shares-file", str(store)]
        if args.lan:
            command += ["--public-url", public_url]
        else:
            command += ["--share-public-url", public_url]
    elif args.share_public_url is not None or args.access_shares_file is not None:
        raise StartupError("Access sharing options require --enable-access-sharing.")
    check_projects(projects)
    check_port(host, port)
    return command, f"{scheme}://{host}:{port}/"


def main(argv=None) -> int:
    args = parser().parse_args(argv)
    try:
        command, url = prepare(args)
        if args.check_only:
            print(f"Configuration and port checks passed: {url}")
            print("No service, Git fetch, GPU command, or agent task was started.")
            return 0
        print(f"Open {url}", flush=True)
        print("Keep this terminal open; Ctrl+C stops this service.", flush=True)
        return subprocess.run(command, cwd=APP_ROOT).returncode
    except (StartupError, OSError) as exc:
        print(f"Startup error: {exc}", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
